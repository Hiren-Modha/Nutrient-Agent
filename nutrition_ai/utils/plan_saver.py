"""
Plan Saver Utility
Saves generated nutrition plans as Markdown (.md) files with metadata.
"""

import os
import re
from datetime import datetime


PLANS_DIR = os.path.join(os.path.dirname(__file__), "..", "plans")


def _safe_filename(name: str) -> str:
    """Convert a display name to a filesystem-safe filename component."""
    return re.sub(r"[^\w\-]", "_", name.strip().lower())


def save_plan_to_md(user_data: dict, plan_text: str) -> str:
    """
    Persist a nutrition plan as a Markdown file.

    Args:
        user_data:  Dictionary with user profile fields.
        plan_text:  Full Markdown text of the generated plan (incl. disclaimer).

    Returns:
        Absolute path to the saved file.
    """
    os.makedirs(PLANS_DIR, exist_ok=True)

    name      = user_data.get("name", "user")
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename  = f"nutrition_plan_{_safe_filename(name)}_{timestamp}.md"
    filepath  = os.path.join(PLANS_DIR, filename)

    # Build the YAML front-matter header
    header = f"""---
title: Personalized Nutrition Plan
generated_by: IBM Granite Nutrition AI (ibm/granite-13b-instruct-v2)
generated_at: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
user_name: {user_data.get("name", "N/A")}
age: {user_data.get("age", "N/A")}
diet_preference: {user_data.get("diet_preference", "N/A")}
medical_history: {user_data.get("medical_history", "None reported")}
location: {user_data.get("city", "")}, {user_data.get("country", "")}
---

# 🥗 Personalized Nutrition Plan — {user_data.get("name", "User")}

> **Generated by:** IBM Granite Nutrition AI  
> **Date:** {datetime.now().strftime("%B %d, %Y")}  
> **Profile:** {user_data.get("diet_preference", "").capitalize()}, Age {user_data.get("age", "N/A")}  
> **Location:** {user_data.get("city", "")}, {user_data.get("country", "")}

"""

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(header + plan_text)

    return os.path.abspath(filepath)


def list_saved_plans() -> list:
    """Return a list of previously saved plan filenames."""
    os.makedirs(PLANS_DIR, exist_ok=True)
    return sorted(
        [f for f in os.listdir(PLANS_DIR) if f.endswith(".md")],
        reverse=True,
    )


def load_plan(filename: str) -> str:
    """Read and return the contents of a saved plan file."""
    filepath = os.path.join(PLANS_DIR, filename)
    if not os.path.isfile(filepath):
        return ""
    with open(filepath, "r", encoding="utf-8") as f:
        return f.read()
