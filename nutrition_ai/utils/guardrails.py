"""
Guardrails Module — AI Ethics & Safety Layer
Implements the HAM (Helpful, Accurate, Mindful) principle and prevents
generation of harmful, discriminatory, or medically irresponsible content.
"""

import re
from typing import Tuple

# ─── Blocked patterns (harmful / irresponsible advice) ────────────────────────
HARMFUL_PATTERNS = [
    r"\bstop (taking|using) (your )?(medication|medicine|insulin|pills)\b",
    r"\b(cure|cures|cured)\b.{0,30}\b(diabetes|cancer|hypertension|disease)\b",
    r"\blose \d{2,3} (kg|pounds|lbs) in (a |one )?(week|day)\b",
    r"\bstarvation diet\b",
    r"\bextreme (fasting|restriction)\b",
    r"\bignore (your )?(doctor|physician|medical advice)\b",
    r"\bsuicide\b|\bself.harm\b",
    r"\bdo not (eat|consume) (anything|food) for (days|weeks)\b",
    r"\bdetox (cleanse|juice) (cures|treats|reverses)\b",
]

# ─── Topics outside the nutrition scope ──────────────────────────────────────
OUT_OF_SCOPE_KEYWORDS = [
    "hack", "exploit", "illegal", "weapon", "violence", "drug abuse",
    "malware", "politics", "religion", "cryptocurrency", "adult content",
]

MEDICAL_DISCLAIMER = """
---
> ⚕️ **Medical Disclaimer**
> This nutrition plan is generated by an AI assistant and is intended for
> **informational and educational purposes only**. It does **not** constitute
> medical advice, diagnosis, or treatment. Always consult a qualified
> healthcare professional or registered dietitian before making significant
> changes to your diet, especially if you have existing medical conditions
> (e.g., diabetes, hypertension, kidney disease, eating disorders).
> Never disregard professional medical advice or delay seeking it because of
> information provided by this AI.
>
> *IBM Granite Nutrition AI — Powered by IBM watsonx.ai*
"""


def validate_user_input(data: dict) -> Tuple[bool, str]:
    """
    Validate collected user data before generating a nutrition plan.
    Returns (is_valid, error_message).
    """
    name = data.get("name", "").strip()
    age  = data.get("age")
    diet = data.get("diet_preference", "").strip().lower()

    if not name or len(name) < 2:
        return False, "Please provide a valid name (at least 2 characters)."

    try:
        age_int = int(age)
        if age_int < 2 or age_int > 120:
            return False, "Please provide a valid age between 2 and 120."
    except (TypeError, ValueError):
        return False, "Age must be a whole number."

    if diet not in ("vegetarian", "veg", "non-vegetarian", "non-veg"):
        return False, "Diet preference must be 'vegetarian' or 'non-vegetarian'."

    return True, ""


def check_prompt_safety(text: str) -> Tuple[bool, str]:
    """
    Screen a user message or generated response for harmful content.
    Returns (is_safe, reason_if_unsafe).
    """
    lower = text.lower()

    for kw in OUT_OF_SCOPE_KEYWORDS:
        if kw in lower:
            return False, (
                f"This query appears to be outside the nutrition domain "
                f"(detected: '{kw}'). Please ask nutrition-related questions only."
            )

    for pattern in HARMFUL_PATTERNS:
        if re.search(pattern, lower):
            return False, (
                "This response has been blocked by the AI safety guardrail because "
                "it contains potentially harmful health advice. Please consult a "
                "qualified healthcare professional."
            )

    return True, ""


def sanitize_response(response: str) -> str:
    """
    Post-process generated text to remove any harmful sentences that may
    have slipped through the model's output.
    """
    sentences = re.split(r'(?<=[.!?])\s+', response)
    safe_sentences = []
    for sentence in sentences:
        safe, _ = check_prompt_safety(sentence)
        if safe:
            safe_sentences.append(sentence)
    return " ".join(safe_sentences)


def add_disclaimer(plan_text: str) -> str:
    """Append the standard medical disclaimer to any generated plan."""
    return plan_text.strip() + "\n\n" + MEDICAL_DISCLAIMER
